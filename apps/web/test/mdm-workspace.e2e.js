// Run through playwright-cli against the disposable Wave 5 fixture only.
async (page) => {
  let checks = 0;
  const check = (condition, message) => {
    if (!condition) throw new Error(message);
    checks++;
  };
  const root = 'http://127.0.0.1:3501';
  const output = '__GEOPS_WAVE5_OUTPUT__';
  if (output.startsWith('__')) throw new Error('Synthetic screenshot directory required');
  await page.setViewportSize({ width: 1366, height: 900 });
  await page.goto(`${root}/status`);
  await page.getByRole('textbox', { name: 'Correo electrónico' }).fill('wave5-limited@example.invalid');
  await page.getByRole('textbox', { name: 'Contraseña' }).fill('synthetic-password-12345678');
  await page.getByRole('button', { name: 'Entrar' }).click();
  await page.waitForURL('**/inventory');
  await page.goto(`${root}/status`);
  await page.locator('.mdm-workspace').waitFor();
  await page.getByText('Requiere permiso para consultar diagnósticos MDM.').waitFor();
  check(true, 'limited user has no diagnostic workspace');
  const limited = await page.evaluate(async () => (await fetch('/v1/admin/mdm/workspace/summary')).status);
  check(limited === 403, 'backend blocks limited user');
  await page.getByRole('button', { name: /Cerrar sesión/ }).click();
  await page.getByRole('textbox', { name: 'Correo electrónico' }).fill('wave5-admin@example.invalid');
  await page.getByRole('textbox', { name: 'Contraseña' }).fill('synthetic-password-12345678');
  await page.getByRole('button', { name: 'Entrar' }).click();
  await page.waitForURL('**/inventory');
  await page.goto(`${root}/status`);
  const workspace = page.locator('.mdm-workspace');
  await workspace.getByRole('heading', { name: 'Diagnóstico y administración MDM' }).waitFor();
  await workspace.getByText('Dispositivos registrados').waitFor();
  check(!(await page.locator('.status-panel').innerText()).includes('No pudimos cargar'), 'connection panel fixture loads');
  check((await workspace.locator('.mdm-metric').first().innerText()).includes('8'), 'eight scoped devices');
  check(!(await workspace.innerText()).includes('Tenant B oculto'), 'other tenant absent');
  await page.screenshot({ path: `${output}/spec05-wave5-dashboard.png`, fullPage: true });
  await workspace.getByRole('button', { name: 'Permisos faltantes' }).click();
  await workspace.getByText('Moto G06 permiso faltante').waitFor();
  check((await workspace.locator('tbody tr').count()) === 1, 'metric opens filtered list');
  await workspace.getByRole('button', { name: 'Ver detalle' }).click();
  await workspace.getByRole('heading', { name: 'Matriz de permisos y configuración' }).waitFor();
  check((await workspace.locator('.mdm-device-detail .notice.error').count()) === 0, 'detail reads existing admin contracts');
  check((await workspace.getByText('Ubicación en segundo plano').count()) > 0, 'permission matrix');
  check((await workspace.getByText('DENIED').count()) === 0, 'raw code not primary label');
  await page.screenshot({ path: `${output}/spec05-wave5-device-detail.png`, fullPage: true });
  await workspace.getByRole('button', { name: 'Diagnósticos' }).click();
  await workspace.getByRole('heading', { name: 'Línea temporal de evidencia' }).waitFor();
  await workspace.getByText('Diagnóstico recibido por GEOPS').waitFor();
  check(true, 'timeline shows persisted diagnostic');
  await workspace.getByRole('button', { name: 'Correcciones' }).click();
  await workspace.getByText('Escritura remota deshabilitada', { exact: false }).waitFor();
  check(true, 'write gate visible');
  await workspace.getByRole('textbox', { name: 'ID numérico de perfil ManageEngine' }).fill('999');
  await workspace.getByRole('textbox', { name: 'Motivo (mínimo 8 caracteres)' }).fill('Solicitud sintética para revisión');
  await workspace.getByRole('button', { name: 'Generar vista previa' }).click();
  await workspace.getByText('Elegible: Sí, para registrar solicitud', { exact: false }).waitFor();
  check(true, 'preview checks one synthetic profile and impact');
  page.once('dialog', (dialog) => dialog.accept());
  await workspace.getByRole('button', { name: 'Confirmar solicitud local' }).click();
  const notice = workspace.getByText(/Solicitud [0-9a-f-]+ registrada para revisión/);
  await notice.waitFor();
  const requestId = (await notice.innerText()).match(/[0-9a-f]{8}-[0-9a-f-]{27,}/)?.[0];
  check(Boolean(requestId), 'request recorded without claiming MDM application');
  const blocked = await page.evaluate(async (id) => {
    const me = await fetch('/v1/admin/auth/me').then((res) => res.json());
    const response = await fetch(`/v1/admin/mdm/remediations/requests/${id}/submit`, {
      method: 'POST', headers: { 'x-csrf-token': me.csrf_token },
    });
    return { status: response.status, body: await response.json() };
  }, requestId);
  check(blocked.status === 503 && blocked.body.error.code === 'mdm_write_disabled', 'real write endpoint stays closed');
  await workspace.getByRole('button', { name: 'Historial y auditoría' }).click();
  await workspace.getByRole('heading', { name: 'Diagnósticos anteriores' }).waitFor();
  await workspace.getByText('perfil 999').waitFor();
  check(true, 'request appears in audited history');
  await workspace.getByRole('button', { name: 'Dispositivos' }).click();
  await workspace.getByRole('button', { name: 'Limpiar filtros' }).click();
  const boxes = workspace.getByRole('checkbox', { name: /Seleccionar SINTÉTICO/ });
  await boxes.nth(0).check();
  await boxes.nth(1).check();
  check((await workspace.getByRole('button', { name: 'Exportar 2 seleccionados (JSON)' }).count()) === 1,
    'multi-device export selection');
  await workspace.getByText('8 dispositivos').waitFor();
  const search = workspace.getByRole('textbox', { name: 'Buscar equipo o agente' });
  await search.fill('batería restringida');
  await workspace.getByRole('button', { name: 'Buscar', exact: true }).click();
  await workspace.getByText('1 dispositivos').waitFor();
  check(true, 'search filters server side');
  await workspace.getByRole('button', { name: 'Limpiar filtros' }).click();
  const exportButton = workspace.getByRole('button', { name: /Exportar/ });
  const download = page.waitForEvent('download');
  await exportButton.click();
  const saved = await download;
  check(saved.suggestedFilename().endsWith('.json'), 'report download');
  const data = await page.evaluate(async () => (await fetch('/v1/admin/mdm/workspace/report')).json());
  check(data.items.length === 8 && !JSON.stringify(data).includes('Tenant B oculto'), 'sanitized scoped report');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: `${output}/spec05-wave5-mobile.png`, fullPage: true });
  check(await workspace.isVisible(), 'mobile workspace visible');
  await page.screenshot({ path: `${output}/spec05-wave5-complete.png`, fullPage: false });
  return { result: 'PASS', checks };
}
