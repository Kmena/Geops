// Playwright CLI run-code fixture. Run only with disposable synthetic API and cached Chrome.
// The final function expression has no semicolon: CLI wraps it as await (<file>)(page).
async (page) => {
  const ensure = (condition, message) => { if (!condition) throw new Error(message); };
  let checks = 0;
  const check = (condition, message) => { ensure(condition, message); checks++; };
  const code = `W2${Date.now()}`;
  await page.setViewportSize({ width: 1280, height: 800 });
  await page.goto('http://127.0.0.1:3501/routes');
  await page.getByRole('heading', { name: 'Rutas reutilizables' }).waitFor();
  check(page.url().endsWith('/routes'), 'route navigation');
  const create = page.locator('section.catalog-section').filter({ has: page.getByRole('heading', { name: 'Crear ruta' }) });
  await create.getByRole('textbox', { name: 'Código' }).fill(code);
  await create.getByRole('textbox', { name: 'Nombre' }).fill('Ruta Web sintética');
  await create.getByRole('textbox', { name: 'Descripción' }).fill('Ruta reutilizable de prueba');
  await create.getByRole('button', { name: 'Crear ruta' }).click();
  await page.waitForURL(/\/routes\/[0-9a-f-]+$/);
  const routeId = page.url().split('/').at(-1);
  check(Boolean(routeId), 'route created in Web');
  await page.getByRole('heading', { name: 'Paradas y geozonas' }).waitFor();
  await page.getByRole('button', { name: 'Publicar versión' }).click();
  await page.getByText('Agrega al menos una parada obligatoria antes de publicar.').waitFor();
  checks++;
  const add = page.locator('section.catalog-section').filter({ has: page.getByRole('heading', { name: 'Agregar sede' }) });
  await add.getByRole('textbox', { name: 'Buscar clientes activos' }).fill('RCLIENT');
  await add.getByRole('button', { name: 'Buscar' }).click();
  await add.getByRole('button', { name: 'RCLIENT · Cliente rutas' }).click();
  await add.getByRole('button', { name: 'MAIN · Principal' }).click();
  await add.getByRole('button', { name: 'BRANCH · Sucursal' }).click();
  const stops = page.locator('.route-stop-list li');
  await stops.nth(1).waitFor();
  check(await stops.count() === 2, 'two sites of one client selected');
  const map = page.getByRole('application', { name: 'Mapa de paradas y geozonas de la ruta' });
  await page.waitForFunction(() => document.querySelectorAll('.route-page .leaflet-overlay-pane path').length >= 4);
  check((await map.boundingBox()).width > 100 && await page.locator('.route-page .leaflet-overlay-pane path').count() >= 4, 'map renders two centers and circles');
  await stops.nth(0).getByRole('spinbutton', { name: 'Permanencia mínima (min)' }).fill('20');
  await stops.nth(1).getByRole('checkbox', { name: 'Obligatoria' }).uncheck();
  await stops.nth(1).getByRole('button', { name: /Subir/ }).click();
  check((await stops.nth(0).textContent()).includes('Sucursal'), 'suggested order changed');
  await page.getByRole('button', { name: 'Guardar borrador' }).click();
  await page.getByText('Borrador guardado. El orden es solo visual.').waitFor();
  const saved = await page.evaluate(async id => fetch(`/v1/admin/routes/${id}`).then(response => response.json()), routeId);
  check(saved.stops.length === 2 && saved.stops.find(stop => stop.site_code === 'MAIN').min_dwell_s === 1200, 'visit requirements persisted');
  await page.reload();
  await stops.nth(1).waitFor();
  check(await stops.count() === 2 && (await stops.nth(0).textContent()).includes('Sucursal'), 'draft restored after reload');
  await page.getByRole('button', { name: 'Publicar versión' }).click();
  await page.getByText('Versión publicada e inmutable.').waitFor();
  const first = await page.evaluate(async id => fetch(`/v1/admin/routes/${id}/revisions/1`).then(response => response.json()), routeId);
  check(first.revision === 1 && first.stops.length === 2, 'first immutable revision available');
  const details = page.locator('section.catalog-section').filter({ has: page.getByRole('heading', { name: 'Ruta Web sintética' }) });
  await details.getByRole('textbox', { name: 'Nombre' }).fill('Ruta Web ajustada');
  await page.getByRole('button', { name: 'Guardar borrador' }).click();
  await page.getByText('Borrador guardado. El orden es solo visual.').waitFor();
  check((await page.evaluate(async id => fetch(`/v1/admin/routes/${id}`).then(response => response.json()), routeId)).has_draft, 'edit published route opens draft');
  await page.getByRole('button', { name: 'Publicar versión' }).click();
  await page.getByText('Versión publicada e inmutable.').waitFor();
  check((await page.evaluate(async id => fetch(`/v1/admin/routes/${id}`).then(response => response.json()), routeId)).published_revision === 2, 'second version published');
  const history = page.locator('section.catalog-section').filter({ has: page.getByRole('heading', { name: 'Versiones publicadas' }) });
  await history.getByRole('button', { name: 'Versión 1 · Ruta Web sintética' }).click();
  await history.getByRole('heading', { name: 'Snapshot v1' }).waitFor();
  check((await history.textContent()).includes('Ruta Web sintética') && (await history.textContent()).includes('Principal'), 'old snapshot visible');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload();
  await page.getByRole('heading', { name: 'Paradas y geozonas' }).waitFor();
  const mobile = await page.evaluate(() => ({ width: innerWidth, scrollWidth: document.documentElement.scrollWidth }));
  check(mobile.scrollWidth <= mobile.width + 2, 'mobile has no horizontal overflow');
  check(await page.getByRole('button', { name: 'Guardar borrador' }).isVisible(), 'mobile editing available');
  return { result:'PASS', checks, routeId, mobile };
}
